#!/usr/bin/env python3
"""Generate references/INDEX.md from the markdown reference library.

Walks references/{category}/*.md, extracts:
  - first H1 (title)
  - all H2 headings (subtopics)
  - "Pattern (...)" mentions (CTF-specific challenge patterns)
  - filename-derived keywords

Emits a YAML-style INDEX.md that workers parse to pick which file to Read.
"""
from __future__ import annotations

import re
from pathlib import Path

REF_ROOT = Path(__file__).resolve().parent.parent / "references"
INDEX_PATH = REF_ROOT / "INDEX.md"

H1_RE = re.compile(r"^#\s+(.+)$", re.M)
H2_RE = re.compile(r"^##\s+(.+)$", re.M)
PATTERN_RE = re.compile(r"\*\*Pattern\s*\(([^)]+)\)", re.I)


def keywords_from_filename(name: str) -> list[str]:
    base = name.removesuffix(".md")
    parts = re.split(r"[-_]", base)
    return [p.lower() for p in parts if p and p.isalnum()]


TRIGGER_CAP = 40
DF_MAX = 25

CAMEL_RE = re.compile(r"[A-Z]+(?![a-z])|[A-Z][a-z0-9]*|[a-z0-9]+")


def split_camel(word: str) -> list[str]:
    parts = CAMEL_RE.findall(word)
    return parts if len(parts) > 1 else []


def extract(md_path: Path) -> dict:
    text = md_path.read_text(encoding="utf-8", errors="replace")
    h1 = H1_RE.search(text)
    h2s = H2_RE.findall(text)
    patterns = PATTERN_RE.findall(text)

    pinned = set(keywords_from_filename(md_path.name))
    triggers = set(pinned)
    for h in h2s:
        for w in re.findall(r"[A-Za-z][A-Za-z0-9]{2,}", h):
            triggers.add(w.lower())
            # Workers type "sandboxed", not "SandboxedEnvironment".
            triggers.update(p.lower() for p in split_camel(w) if len(p) > 2)
    for p in patterns:
        triggers.add(p.split(",")[0].strip().lower())

    common = {"and", "the", "for", "ctf", "with", "from", "via", "techniques",
              "attacks", "advanced", "specific", "techniques", "part", "tools",
              "based", "using", "field", "notes", "reference"}
    triggers -= common
    pinned -= common

    return {
        "title": h1.group(1).strip() if h1 else md_path.stem,
        "subtopics": h2s[:8],
        "patterns": patterns[:6],
        "triggers": triggers,
        "pinned": pinned,
        "size_lines": len(text.splitlines()),
    }


def select_triggers(infos: list[dict], cap: int = TRIGGER_CAP,
                    df_max: int = DF_MAX) -> None:
    """Keep the most *discriminative* triggers, not the alphabetically first.

    A file can yield 90+ candidate keywords; the cap keeps INDEX.md small enough
    for a worker to Read. Selecting with sorted()[:cap] threw away everything
    after roughly 'c', so searches for late-alphabet terms (svn, shebang, xxe)
    silently missed. Rank by document frequency instead: a term in few files
    identifies this file, one in a third of them does not. Terms above df_max
    are dropped outright — "injection" (34 files) and "bypass" (51) cannot
    discriminate and were crowding out names workers actually search for.
    """
    df: dict[str, int] = {}
    for info in infos:
        for t in info["triggers"]:
            df[t] = df.get(t, 0) + 1

    for info in infos:
        pinned = info["pinned"]
        usable = {t for t in info["triggers"] if df[t] <= df_max} - pinned
        rest = sorted(usable, key=lambda t: (df[t], t))
        info["triggers"] = sorted(pinned | set(rest[: max(0, cap - len(pinned))]))


def build_index() -> str:
    out = ["# Reference Library Index",
           "",
           "Auto-generated by `tools/build_ref_index.py`. Workers Read this index",
           "first, then Read the matching `.md` file under `references/<category>/`.",
           "",
           "**How to use as a worker:**",
           "1. After recon (Phase 1), match challenge keywords against `triggers`.",
           "2. Pick 1-3 files with best match. **Do NOT Read every file in a category.**",
           "3. If no trigger matches, fall back to `_CATEGORY_OVERVIEW.md`.",
           ""]

    scanned = [(d, md, extract(md))
               for d in sorted(REF_ROOT.iterdir()) if d.is_dir()
               for md in sorted(d.glob("*.md"))]
    select_triggers([info for _, _, info in scanned])

    for category_dir in sorted(REF_ROOT.iterdir()):
        if not category_dir.is_dir():
            continue
        out.append(f"## {category_dir.name}")
        out.append("")
        for d, md, info in scanned:
            if d != category_dir:
                continue
            rel = f"references/{category_dir.name}/{md.name}"
            out.append(f"### `{rel}`")
            out.append(f"- **title**: {info['title']}")
            out.append(f"- **size**: {info['size_lines']} lines")
            if info["patterns"]:
                pats = ", ".join(info["patterns"])
                out.append(f"- **patterns**: {pats}")
            if info["subtopics"]:
                subs = " | ".join(info["subtopics"][:6])
                out.append(f"- **subtopics**: {subs}")
            out.append(f"- **triggers**: {', '.join(info['triggers'])}")
            out.append("")
        out.append("")

    return "\n".join(out)


if __name__ == "__main__":
    INDEX_PATH.write_text(build_index(), encoding="utf-8")
    print(f"Wrote {INDEX_PATH} ({INDEX_PATH.stat().st_size} bytes)")
